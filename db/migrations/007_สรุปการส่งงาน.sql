create table if not exists report_rounds (
  id integer generated by default as identity primary key,
  doc_type text collate "C" not null,
  academic_year integer not null,
  semester integer not null,
  due_date text collate "C" not null default '',
  doc_no text collate "C" not null default '',
  doc_date text collate "C" not null default '',
  sign_reporter text collate "C" not null default '',
  sign_head text collate "C" not null default '',
  sign_deputy text collate "C" not null default '',
  sign_director text collate "C" not null default '',
  note_on integer not null default 1,
  end_note text collate "C" not null default '',
  color_mode text collate "C" not null default 'color',
  note_notsent integer not null default 1,
  note_late integer not null default 1,
  red_notsent integer not null default 1,
  red_late integer not null default 0,
  updated_at text collate "C" not null default '',
  unique (doc_type, academic_year, semester)
);
create table if not exists report_adjusts (
  id integer generated by default as identity primary key,
  teacher_id integer not null references users(id) on delete cascade,
  doc_type text collate "C" not null,
  academic_year integer not null,
  semester integer not null,
  result text collate "C" not null,
  situation text collate "C" not null default '',
  reason text collate "C" not null default '',
  note text collate "C" not null default '',
  extend_date text collate "C" not null default '',
  until_date text collate "C" not null default '',
  updated_by_name text collate "C" not null default '',
  updated_at text collate "C" not null default '',
  unique (teacher_id, doc_type, academic_year, semester)
);
update schema_version set version = 7;
