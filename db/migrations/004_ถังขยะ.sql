create table if not exists trash_log (
  id integer generated by default as identity primary key,
  ref text collate "C" not null,
  trash_ref text collate "C",
  name text collate "C" not null default '',
  mime text collate "C" not null default '',
  size bigint not null default 0,
  kind text collate "C" not null default '',
  was_current integer not null default 1,
  submission_id integer,
  teacher_id integer,
  label text collate "C" not null default '',
  snapshot text collate "C" not null default '{}',
  deleted_at text collate "C" not null,
  deleted_by integer,
  deleted_by_name text collate "C" not null default '',
  restored_at text collate "C",
  restored_by_name text collate "C",
  restored_kind text collate "C",
  restored_sub integer
);
create index if not exists idx_trash_at on trash_log (deleted_at);
update schema_version set version = 4;
