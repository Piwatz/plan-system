-- รุ่น 8 (31 ต.ค. 2569) คำของฉันในช่องความเห็น (ฟังก์ชันเสริม myphrases) แต่ละคนมีรายการของตัวเอง
-- รันซ้ำได้ไม่พัง · มีตารางใหม่ รัน db/supabase-lockdown.sql ซ้ำหลังรันไฟล์นี้
create table if not exists user_phrases (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  kind text collate "C" not null,
  text text collate "C" not null,
  updated_at text collate "C" not null default '',
  unique (user_id, kind, text)
);
update schema_version set version = 8;
