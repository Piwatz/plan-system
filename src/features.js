// คืน { web, pdf } หรือ null ถ้าปิดฟังก์ชันอยู่ (ใช้แบบเดิม)
function noteSign(settings) {
  const s = settings || db.refs().settings;
  if (!isOn(s, 'notesign')) return null;
  const pick = (kind) => (NOTE_SIGN[kind].some((o) => o.key === s[`note_sign_${kind}`]) ? s[`note_sign_${kind}`] : NOTE_SIGN[kind][0].key);
  return { web: pick('web'), pdf: pick('pdf') };
}

