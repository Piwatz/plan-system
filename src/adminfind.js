// ปุ่มลัดคำที่ค้นบ่อย แสดงตอนยังไม่พิมพ์
const POPULAR = ['ลายเซ็น', 'รหัสผ่าน', 'ปก', 'สำรองข้อมูล', 'ภาคเรียน', 'ธีม'];

// รายการที่ส่งให้หน้าเว็บ: ฟังก์ชันเสริมทุกตัว (พร้อมสถานะ) และหน้าหรือหัวข้อที่เปิดใช้อยู่
function items(settings, ff) {
  const feats = features.FEATURES.map((f) => ({
    kind: 'feature',
    key: f.key,
    title: f.title,
    desc: f.desc,
    who: f.who,
    on: features.isOn(settings, f.key),
    href: `/admin/features?found=1#f-${f.key}`,
  }));
  const places = PLACES.filter((p) => !p.ff || ff[p.ff]).map((p) => ({
    kind: 'place',
    title: p.title,
    desc: p.desc,
    where: p.where,
    words: p.words || '',
    href: p.href.includes('#') ? p.href.replace('#', `${p.href.includes('?') ? '&' : '?'}found=1#`) : p.href,
  }));
  return { items: [...places, ...feats], synonyms: SYNONYMS, popular: POPULAR };
}

module.exports = { PLACES, SYNONYMS, POPULAR, items };
